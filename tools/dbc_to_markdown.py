"""Generate dbc/SIGNALS.md, the CAN signal reference, from the dbc files.

The dbc files are the single source of truth for what every CAN message and
signal means: edit those, then regenerate the reference from the top of the
repository with

    python3 tools/dbc_to_markdown.py

Tests/test_dbc_docs.py fails if dbc/SIGNALS.md is out of date.
"""
from pathlib import Path

import cantools

# The bit layout diagram is the one `cantools dump` prints. It lives in an
# internal cantools module, so the reference simply leaves it out if a cantools
# version moves it.
try:
    from cantools.subparsers.dump.formatting import layout_string
except ImportError:  # pragma: no cover
    layout_string = None

REPO_ROOT = Path(__file__).resolve().parent.parent
DBC_DIR = REPO_ROOT / "dbc"
OUTPUT = DBC_DIR / "SIGNALS.md"

# Vector's DBC editor keeps signals that are not in any message in this
# pseudo message. It is never sent on the bus, so it is left out.
VECTOR_INDEPENDENT_SIGNALS_ID = 0xC0000000


def load(dbc_file: Path) -> cantools.database.Database:
    return cantools.database.load_file(dbc_file, strict=True)


def dbc_files() -> list:
    return sorted(DBC_DIR.glob("*.dbc"))


def messages(db: cantools.database.Database) -> list:
    return sorted(
        (m for m in db.messages if m.frame_id != VECTOR_INDEPENDENT_SIGNALS_ID),
        key=lambda m: m.frame_id,
    )


def todos(db: cantools.database.Database) -> list:
    """(where, comment) for every node, message and signal comment with a TODO."""
    found = [(f"device {n.name}", n.comment) for n in db.nodes if "TODO" in (n.comment or "")]
    for m in messages(db):
        if "TODO" in (m.comment or ""):
            found.append((f"message {m.name}", m.comment))
        for s in m.signals:
            if "TODO" in (s.comment or ""):
                found.append((f"signal {m.name}.{s.name}", s.comment))
    return found


def cell(text) -> str:
    """Make text safe for a markdown table cell."""
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def anchor(message) -> str:
    return f"{message.name}-0x{message.frame_id:03x}".lower()


def number(x) -> str:
    return f"{x:g}"


def scaling(signal) -> str:
    if signal.is_float:
        return "none (sent as a decimal number)"
    if signal.scale == 1 and signal.offset == 0:
        return "none"
    text = f"raw x {number(signal.scale)}"
    if signal.offset:
        text += f" + {number(signal.offset)}"
    return text


def value_range(signal) -> str:
    if signal.minimum is None and signal.maximum is None:
        return ""
    if not signal.minimum and not signal.maximum:  # [0|0]: not set in the dbc
        return ""
    return f"{number(signal.minimum)} to {number(signal.maximum)}"


def values(signal) -> str:
    if not signal.choices:
        return ""
    return ", ".join(f"{k} = {v}" for k, v in signal.choices.items())


def source(message) -> str:
    return message.senders[0] if message.senders else ""


def measurement(message) -> str:
    """InfluxDB measurement name, as written by Receiver/storer_extension.py."""
    return f"{source(message)}/{message.name}"


def render() -> str:
    out = [
        "# CAN signal reference",
        "",
        "<!-- Generated by tools/dbc_to_markdown.py from the dbc files. Do not edit:",
        "     edit the dbc files, then run python3 tools/dbc_to_markdown.py -->",
        "",
        "_Generated from the `.dbc` files in this directory. To change anything here, "
        "edit the `.dbc` file and regenerate (see [README.md](README.md))._",
        "",
        "Every CAN message the receiver can decode, what each signal means, and where "
        "to find it in InfluxDB / Grafana. New to CAN? Read [README.md](README.md) first.",
        "",
    ]

    databases = [(f, load(f)) for f in dbc_files()]

    # contents
    out += ["## Contents", ""]
    for f, db in databases:
        out.append(f"* [{f.name}](#{f.stem.lower().replace('_', '')})")
        for m in messages(db):
            out.append(f"  * [{m.name}](#{anchor(m)}) (0x{m.frame_id:03X}, from {source(m)})")
    all_todos = [(f, t) for f, db in databases for t in todos(db)]
    out += ["* [Still to be documented](#still-to-be-documented)", ""]

    for f, db in databases:
        # explicit anchor, so the contents link does not depend on how the
        # markdown renderer turns "wavesculptor_22.dbc" into an id
        out += [f'<a id="{f.stem.lower().replace("_", "")}"></a>', ""]
        out += [f"## {f.name}", ""]
        if db.nodes:
            out += ["| Device (Source) | Description |", "|---|---|"]
            out += [f"| `{n.name}` | {cell(n.comment)} |" for n in db.nodes]
            out.append("")
        for m in messages(db):
            out += [f'<a id="{anchor(m)}"></a>', ""]
            out += [f"### {m.name} (0x{m.frame_id:03X})", ""]
            if m.comment:
                out += [m.comment, ""]
            out += [
                "| | |",
                "|---|---|",
                f"| From | `{source(m)}` |",
                f"| CAN ID | 0x{m.frame_id:03X} ({m.frame_id}) |",
                f"| Length | {m.length} bytes |",
                f"| Sent every | {f'{m.cycle_time} ms' if m.cycle_time else 'not known'} |",
                f'| InfluxDB measurement | `"{measurement(m)}"` |',
                "",
            ]
            if m.signals:
                out += [
                    "| Signal (InfluxDB field) | Meaning | Unit | Scaling | Range | Values |",
                    "|---|---|---|---|---|---|",
                ]
                for s in m.signals:
                    out.append(
                        f"| `{s.name}` | {cell(s.comment)} | {cell(s.unit)} | {scaling(s)} "
                        f"| {value_range(s)} | {cell(values(s))} |"
                    )
                out.append("")
                first = m.signals[0].name
                out += [
                    "Example InfluxDB query:",
                    "",
                    "```",
                    f'SELECT "{first}" FROM "{measurement(m)}" WHERE time > now() - 1h',
                    "```",
                    "",
                ]
                if layout_string is not None:
                    out += [
                        "<details><summary>Bit layout</summary>",
                        "",
                        "```",
                        layout_string(m),
                        "```",
                        "",
                        "</details>",
                        "",
                    ]
            else:
                out += ["This message carries no data.", ""]

    out += ["## Still to be documented", ""]
    if all_todos:
        out += [
            f"{len(all_todos)} comments in the dbc files still contain a TODO:",
            "",
            "| File | Where | Comment |",
            "|---|---|---|",
        ]
        out += [f"| {f.name} | {cell(where)} | {cell(c)} |" for f, (where, c) in all_todos]
    else:
        out.append("Nothing: every message and signal is fully documented.")
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
